"""Generate NivalisProof/Patterns.lean from nivalis' src/patterns/mod.rs.

Usage (from the repository root):
    python3 -I lean/gen_patterns.py src/patterns/mod.rs > lean/NivalisProof/Patterns.lean

Each `impl Pattern for T { NAME, HANDSHAKE }` block becomes a ScalingTrust
`Noise.HandshakePattern`.  nivalis stores pre-messages as `&[Token]`; the
generator checks they contain only `Token::E` / `Token::S` (anything else would
hit the `unreachable!()` in `mix_pre_messages_*`), so they fit ScalingTrust's
`PreMessagePattern = List KeyKind`.
"""
import re, sys

src = open(sys.argv[1]).read()
rx = re.compile(
    r'impl Pattern for (\w+) \{\s*const NAME: &\'static str = "(\w+)";.*?'
    r'pre_messages_initiator: &\[(.*?)\],\s*pre_messages_responder: &\[(.*?)\],\s*'
    r'messages: &\[(.*?)\],\s*\};', re.S)

MSG = {"E": ".e", "S": ".s", "EE": ".ee", "ES": ".es", "SE": ".se", "SS": ".ss", "PSK": ".psk"}
PRE = {"E": ".e", "S": ".s"}

def toks(s, table):
    out = []
    for t in s.split(","):
        t = t.strip()
        if t:
            out.append(table[t.removeprefix("Token::")])  # KeyError = unexpected token
    return "[" + ", ".join(out) + "]"

entries = []
for m in rx.finditer(src):
    ty, name, pi, pr, msgs = m.groups()
    assert ty == name, (ty, name)
    ms = re.findall(r'tokens: &\[(.*?)\]', msgs, re.S)
    entries.append(f'  {{ name := "{name}", initiatorPre := {toks(pi, PRE)}, responderPre := {toks(pr, PRE)},\n'
                   f'    messages := [{", ".join(toks(x, MSG) for x in ms)}] }}')

assert src.count("impl Pattern for") == len(entries), "regex missed a pattern"
print("""/-
  GENERATED by gen_patterns.py from nivalis src/patterns/mod.rs -- do not edit.
  One entry per `impl Pattern for _` block, in source order.
-/
import ScalingTrust.Noise.Pattern

namespace NivalisProof
open Noise

/-- nivalis' handshake patterns (`P::NAME`, `P::HANDSHAKE`), in source order. -/
def nivalisPatterns : List HandshakePattern := [""")
print(",\n".join(entries))
print("""]

end NivalisProof""")
